#!/usr/bin/env python3
"""Deterministically binds an *analysis variant* kernel into a timing-only harness.

This is the measurement path for the phases the correctness harness cannot
serve:

  * Phase 0.6 baseline per-case timing (the "variant" is `base.py` itself);
  * floor probes    -- the compute-only / transfer-only cuts (general_floor.md);
  * attribution     -- one stage removed per variant (general_attribution.md);
  * gap probes      -- work held constant, schedule perturbed
                       (general_gap_probing.md).

Every variant in the middle three categories returns wrong numbers **on
purpose**: the compute-only cut reads uninitialised memory, an ablation hands
its matmul a stand-in operand, the skeleton computes nothing at all. A
correctness check would fail on all of them and carry zero information, so
`assemble_test_run.py` is the wrong tool for them and this is the right one.
(Shippable changes still go through `assemble_test_run.py`, which always
checks. The two regimes are disjoint.)

Why this is a script and not an instruction to an agent:

  * **The timing protocol is not re-authored per variant.** `benchmark()` is
    lifted verbatim out of `test_harness_template.py`, so a floor measured
    here and an `optimized_time_ms` measured by the correctness harness are
    the same kind of number -- which is the only thing that makes
    `gap = actual - floor` a legal subtraction.
  * **`get_inputs()` is the run's own, unchanged**, so every variant is timed
    on exactly the cases the kernel is scored on.
  * The variant's source is `exec()`'d into its own namespace, so its
    module-level `kernel` helper can never collide with anything -- same
    reasoning as `assemble_test_harness.py`'s docstring.

Output contract on STDOUT, parsed by maxkernel-worker:

    VARIANT: <label>
    CASE_TIME_<idx>: <ms>          one line per get_inputs() case
    CASE_ERROR_<idx>: <message>    instead of the above, if that case raised
    GEOMEAN_TIME: <ms>             geometric mean over the cases that ran

A case that raises is reported and skipped rather than killing the run: a
variant that is infeasible on one shape (a depth-8 buffer that exceeds VMEM,
say) is still informative on the others, and per general_autotune.md §3.3 the
failure is itself a hard bound worth recording.
"""

import argparse
import re
import sys
from pathlib import Path

TOOLS_DIR = Path(__file__).parent
TEMPLATE_PATH = TOOLS_DIR / "test_harness_template.py"

# `benchmark()` runs from its `def` line to the next top-level `def`.
_BENCH_RE = re.compile(r"^def benchmark\(.*?(?=^def |\Z)", re.S | re.M)

_PREAMBLE = '''\
"""Timing-only harness for one MaxKernel analysis variant.

Generated by tools/assemble_variant_run.py -- do not edit by hand.

There is deliberately NO correctness check in this file. Analysis variants
(floor cuts, ablations, gap probes) are expected to compute the wrong answer;
what must hold instead is that their shapes and instruction mix stay
representative. See skill/guides/general_attribution.md section 5.
"""

# `get_inputs` and `variant_computation` are bound into this module's
# namespace by exec() below, which static analysis cannot see.
# pyright: reportUndefinedVariable=false

import math
import sys
import time
import traceback

import jax
import jax.numpy as jnp
'''

_MAIN = """

def main():
  try:
    raw_inputs = get_inputs()  # noqa: F821 -- bound above

    if isinstance(raw_inputs, list):
      inputs_list = raw_inputs
    elif isinstance(raw_inputs, tuple) and len(raw_inputs) == 2:
      inputs_list = [raw_inputs]
    else:
      raise ValueError(
          "get_inputs() must return a list of tuples or a single "
          "(dynamic_args, static_args) tuple."
      )

    print(f"VARIANT: {VARIANT_LABEL}")

    times = []
    for idx, inputs in enumerate(inputs_list):
      if not isinstance(inputs, tuple) or len(inputs) != 2:
        raise ValueError(
            "Each input config must return exactly 2 elements: "
            f"(dynamic_args, static_args). Got: {type(inputs)}"
        )
      dynamic_args, static_args = inputs
      args = tuple(dynamic_args) + tuple(static_args)
      static_argnums = tuple(range(len(dynamic_args), len(args)))

      try:
        elapsed = benchmark(variant_computation, args, static_argnums)  # noqa: F821
      except Exception as exc:  # pylint: disable=broad-except
        # One infeasible shape does not invalidate the others.
        print(f"CASE_ERROR_{idx}: {type(exc).__name__}: {exc}")
        traceback.print_exc()
        continue

      times.append(elapsed)
      print(f"CASE_TIME_{idx}: {elapsed * 1000:.6f} ms")

    valid = [t for t in times if t > 0]
    if not valid:
      print("GEOMEAN_TIME: none")
      sys.exit(1)
    geo_mean = math.exp(sum(math.log(t) for t in valid) / len(valid))
    print(f"GEOMEAN_TIME: {geo_mean * 1000:.6f} ms")

  except Exception as exc:  # pylint: disable=broad-except
    print(f"ERROR: {exc}")
    traceback.print_exc()
    sys.exit(1)


if __name__ == "__main__":
  main()
"""


def extract_benchmark(template_src: str) -> str:
  """Lifts `benchmark()` out of the shared harness template, verbatim."""
  match = _BENCH_RE.search(template_src)
  if not match:
    raise ValueError(
      f"{TEMPLATE_PATH} has no top-level `def benchmark(` -- the variant "
      "harness cannot be assembled without reusing the run's own timing "
      "protocol, and copying a second one here would make floors and "
      "measured times non-comparable."
    )
  return match.group(0).rstrip() + "\n"


def assemble(
  variant_kernel_path: str,
  get_inputs_path: str,
  output_path: str,
  label: str,
) -> None:
  variant_src = Path(variant_kernel_path).read_text()
  # `computation` may be defined (`def computation(...)`) or bound to an
  # existing function (`computation = workload`). Both leave a module-level
  # `computation` for the exec'd namespace below, so accept either; only a
  # source with neither can fail to bind. Mirrors assemble_test_harness.py.
  if not re.search(
    r"^(?:def\s+computation\b|computation\s*=)", variant_src, re.M
  ):
    raise ValueError(
      f"{variant_kernel_path} has no module-level `computation` function -- "
      "cannot bind it as variant_computation. Analysis variants keep the "
      "same entry point name as the kernel they were cut from."
    )

  get_inputs_src = Path(get_inputs_path).read_text()
  if "def get_inputs" not in get_inputs_src:
    raise ValueError(f"{get_inputs_path} has no `get_inputs()` function.")

  benchmark_src = extract_benchmark(TEMPLATE_PATH.read_text())

  parts = [
    _PREAMBLE,
    f"VARIANT_LABEL = {label!r}",
    "",
    "# =====================================================================",
    f"# benchmark(), lifted verbatim from {TEMPLATE_PATH}.",
    "# Same warmup count, same run count, same layout handling as the",
    "# correctness harness -- so times measured here are subtractable from",
    "# times measured there.",
    "# =====================================================================",
    benchmark_src,
    "# =====================================================================",
    f"# get_inputs(), from {get_inputs_path} -- the run's own cases,",
    "# unchanged, so every variant is timed on what the kernel is scored on.",
    "# =====================================================================",
    get_inputs_src,
    "",
    "# =====================================================================",
    f"# Analysis variant, embedded verbatim from {variant_kernel_path}.",
    "# Executed into its own namespace -- see this script's module docstring.",
    "# =====================================================================",
    f"_VARIANT_SRC = {variant_src!r}",
    "_variant_ns = {}",
    "exec(compile(_VARIANT_SRC, "
    + repr(str(variant_kernel_path))
    + ", 'exec'), _variant_ns)",
    "variant_computation = _variant_ns['computation']",
    _MAIN,
  ]

  Path(output_path).write_text("\n".join(parts))
  print(f"Assembled variant timing script at {output_path} (label: {label})")


def main():
  parser = argparse.ArgumentParser(
    description=(
      "Bind an analysis variant kernel into a timing-only harness "
      "(no correctness check, by design)."
    )
  )
  parser.add_argument(
    "variant_kernel_path",
    help="Path to the variant kernel (must define `computation`).",
  )
  parser.add_argument(
    "get_inputs_path", help="Path to the run's get_inputs.py."
  )
  parser.add_argument("output_path", help="Path to write the runnable script.")
  parser.add_argument(
    "--label",
    default=None,
    help=(
      "Short name for this variant, echoed as `VARIANT:` on STDOUT "
      "(defaults to the variant file's stem). Name what was REMOVED, and "
      "be consistent: 'no-transfer' and 'transfer-only' are opposite "
      "conventions and mixing them guarantees a misread later."
    ),
  )
  args = parser.parse_args()

  label = args.label or Path(args.variant_kernel_path).stem

  try:
    assemble(
      args.variant_kernel_path,
      args.get_inputs_path,
      args.output_path,
      label,
    )
  except Exception as e:  # pylint: disable=broad-except
    print(f"Failed to assemble variant run: {e}", file=sys.stderr)
    sys.exit(1)


if __name__ == "__main__":
  main()
