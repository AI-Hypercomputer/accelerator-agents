#!/usr/bin/env python3
"""Turns a forward base.py into a training-step base.py (Phase 0.85).

Runs only for jobs with `backward.from: "autodiff"`. The gradients are taken by
JAX's autodiff, not written by anyone, so the result is exactly as trustworthy
as the forward port (checked in Phase 0.8 or 0.7 when that was possible). No
LLM is involved.

What it writes:

  <dir>/base_fwd.py  the forward, unchanged (kept for the record, and the
                     source this tool reads on every re-run)
  <dir>/base.py      the forward source verbatim, followed by a generated
                     wrapper that rebinds `computation` to one of:

    (default)        computation(cotangent, *forward_args)
                       -> (forward_output, gradients)
    --fixed-forward  computation(cotangent, *forward_args) -> gradients

By default both passes are optimized: `computation` is one training step
built from `forward_pass(*forward_args) -> (forward_output, saved)` and
`backward_pass(saved, cotangent) -> gradients`, kept apart by an optimization
barrier as they are in training. The kernel chooses what `saved` holds, and
`assemble_test_run.py` scores its two passes through this file's
`training_step`, so the result is a ready `jax.custom_vjp` pair.

With --fixed-forward the user's forward stays fixed and only the backward is
optimized. It receives what a fixed forward can always hand it -- the forward
inputs -- and recomputes anything else it needs, as the baseline's jax.vjp
does.

The forward stays readable at the top of base.py on purpose: the planner and
implementer read base.py to learn what they are optimizing, and the math of a
backward pass is the forward's math.

`cotangent` is the FIRST argument so it is a dynamic argument: the harness
treats the trailing arguments of each `get_inputs()` case as static, and the
forward's static arguments must stay last. It must match the forward's output
pytree, shapes and dtypes; values for non-float outputs (indices, counts) are
ignored, since those carry no gradient. Gradients are a tuple, one per
differentiated argument, in forward-argument order.

Which arguments are differentiated:
  --wrt NAME ...  those parameters of the forward `computation`, by name
  (default)       every argument that is, or holds, a floating-point array,
                  decided at trace time. Within a pytree argument only the
                  floating-point leaves are differentiated; the others get
                  None. Integer arrays and scalars (static arguments) are
                  never differentiated, and a forward with nothing to
                  differentiate fails instead of returning no gradients

Idempotent: base_fwd.py is written only on success, and once it exists it is
the source, so a re-run never wraps an already-wrapped base.py.

Exit codes:
  0  base.py written
  1  could not generate (no `computation`, unknown --wrt name, name clash,
     a pallas_call in the forward)
"""

import argparse
import ast
import re
import shutil
import sys
from pathlib import Path

MARKER = "# Generated by tools/make_vjp_base.py"
FORWARD_NAME = "forward_computation"
# Names the wrapper binds in the forward's module namespace. Its imports are
# aliased so they cannot rebind a name the forward uses (`np`, `jnp`, ...).
RESERVED = (
  FORWARD_NAME,
  "forward_pass",
  "backward_pass",
  "training_step",
  "_vjp",
  "_differentiable",
  "_float_leaf",
  "_pull",
  "_vjp_jax",
  "_vjp_jnp",
  "_vjp_np",
  "_WRT_POSITIONS",
)

_HEADER = """

# =====================================================================
{marker} from the forward above
# (kept unchanged in base_fwd.py). Do not edit.
#
#   computation(cotangent, *forward_args) -> {returns}
#
{summary}
#
# `cotangent` matches {forward}'s output (same pytree, shapes and
# dtypes); values for non-float outputs are ignored. Gradients are a
# tuple, one per differentiated argument, in forward-argument order.
# Differentiated: {wrt_desc}.
#
# An optimized version must write the backward explicitly: pallas_call
# has no autodiff rule, so jax.vjp cannot derive it from a Pallas kernel.
# =====================================================================
import jax as _vjp_jax
import jax.numpy as _vjp_jnp
import numpy as _vjp_np

{forward} = computation
_WRT_POSITIONS = {positions!r}


def _float_leaf(l):
  # Arrays only: a NumPy scalar has a dtype too, but it is a static argument.
  return isinstance(
    l, (_vjp_jax.Array, _vjp_np.ndarray)
  ) and _vjp_jnp.issubdtype(l.dtype, _vjp_jnp.floating)


def _differentiable(a):
  return any(_float_leaf(l) for l in _vjp_jax.tree_util.tree_leaves(a))


def _vjp(args):
  if _WRT_POSITIONS is None:
    pos = tuple(i for i, a in enumerate(args) if _differentiable(a))
    if not pos:
      raise ValueError(
        "make_vjp_base: the forward has no floating-point array argument "
        "to differentiate"
      )
  else:
    pos = _WRT_POSITIONS

  # Only the floating-point leaves of each argument are differentiated; the
  # others (index tables in a params dict, ...) are held fixed and get None
  # in place of a gradient.
  split = [_vjp_jax.tree_util.tree_flatten(args[i]) for i in pos]
  masks = [[_float_leaf(l) for l in leaves] for leaves, _ in split]

  def _fwd(*diff_leaves):
    it = iter(diff_leaves)
    full = list(args)
    for i, (leaves, tree), mask in zip(pos, split, masks):
      full[i] = tree.unflatten(
        [next(it) if m else l for l, m in zip(leaves, mask)]
      )
    return {forward}(*full)

  trees = [tree for _, tree in split]  # static structure only, no tracers

  def _regroup(vjp, cotangent):
    it = iter(vjp(cotangent))
    return tuple(
      tree.unflatten([next(it) if m else None for m in mask])
      for tree, mask in zip(trees, masks)
    )

  diff = [l for (leaves, _), mask in zip(split, masks)
          for l, m in zip(leaves, mask) if m]
  out, vjp = _vjp_jax.vjp(_fwd, *diff)
  # A Partial stays a pytree, so the pullback's saved arrays still go through
  # training_step's barrier.
  return out, _vjp_jax.tree_util.Partial(_regroup, vjp)


def _pull(vjp, out, cotangent):
  # Non-float outputs (indices, counts) carry no gradient; jax.vjp wants a
  # float0 cotangent for them, which cannot be a jit argument. result_type
  # and np.shape also cover outputs returned as plain Python numbers.
  cotangent = _vjp_jax.tree_util.tree_map(
    lambda o, c: (
      c
      if _vjp_jnp.issubdtype(_vjp_jnp.result_type(o), _vjp_jnp.inexact)
      else _vjp_np.zeros(_vjp_np.shape(o), dtype=_vjp_jax.dtypes.float0)
    ),
    out,
    cotangent,
  )
  return vjp(cotangent)
"""

_TRAINING_STEP = """

def forward_pass(*args):
  out, vjp = _vjp(args)
  return out, (vjp, out)


def backward_pass(saved, cotangent):
  return _pull(*saved, cotangent)


def training_step(forward_pass, backward_pass):
  def step(cotangent, *args):
    out, saved = forward_pass(*args)
    # The forward finishes before the backward starts, as in training: no
    # work on the cotangent can be merged into the forward. Only arrays go
    # through the barrier; static values in `saved` (e.g. eps) stay static.
    leaves, tree = _vjp_jax.tree_util.tree_flatten((out, saved, cotangent))
    arrays = [i for i, l in enumerate(leaves) if isinstance(l, _vjp_jax.Array)]
    kept = _vjp_jax.lax.optimization_barrier([leaves[i] for i in arrays])
    for i, l in zip(arrays, kept):
      leaves[i] = l
    out, saved, cotangent = _vjp_jax.tree_util.tree_unflatten(tree, leaves)
    return out, backward_pass(saved, cotangent)

  return step


computation = training_step(forward_pass, backward_pass)
"""

_FIXED_FORWARD = """

def computation(cotangent, *args):
  out, vjp = _vjp(args)
  return _pull(vjp, out, cotangent)
"""

_SUMMARIES = {
  True: (
    "(forward_output, gradients)",
    """# One training step, built from two passes kept apart as in training:
#   forward_pass(*forward_args) -> (forward_output, saved)
#   backward_pass(saved, cotangent) -> gradients
# An optimized version defines both, choosing what `saved` holds (static
# values such as eps may go in it too), and
# `computation = training_step(forward_pass, backward_pass)` (copy
# training_step). The harness scores its forward_pass and backward_pass
# through the training_step below, so they can be used as a
# jax.custom_vjp pair.""",
    _TRAINING_STEP,
  ),
  False: (
    "gradients",
    "# The backward only; the user's forward stays fixed.",
    _FIXED_FORWARD,
  ),
}


class VjpError(Exception):
  pass


def _computation_params(tree):
  """Positional parameter names of the module-level `computation`.

  Follows one alias (`computation = workload`). Returns None when names
  cannot be mapped to positions: the signature takes *args, or `computation`
  is bound to something other than a module-level function (`jax.jit(f)`).
  """
  funcs = {
    n.name: n
    for n in tree.body
    if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
  }
  target = "computation"
  for n in tree.body:
    if (
      isinstance(n, ast.Assign)
      and any(
        isinstance(t, ast.Name) and t.id == "computation" for t in n.targets
      )
      and isinstance(n.value, ast.Name)
    ):
      target = n.value.id
  fn = funcs.get(target)
  if fn is None or fn.args.vararg is not None:
    return None
  return [a.arg for a in fn.args.posonlyargs + fn.args.args]


def generate(fwd_src, wrt=None, optimize_forward=True):
  """Returns the generated base.py source for a forward base.py source."""
  if MARKER in fwd_src:
    raise VjpError(
      "the forward source is already a generated base.py; restore "
      "the forward (base_fwd.py) instead of wrapping twice"
    )
  if not re.search(r"^(?:def\s+computation\b|computation\s*=)", fwd_src, re.M):
    raise VjpError(
      "no module-level `computation` function (or `computation = ...`) found "
      "in the forward base.py"
    )
  tree = ast.parse(fwd_src)
  if any(
    (isinstance(n, ast.Attribute) and n.attr == "pallas_call")
    or (isinstance(n, ast.Name) and n.id == "pallas_call")
    for n in ast.walk(tree)
  ):
    raise VjpError(
      "the forward base.py calls pallas_call, which has no autodiff rule; "
      "jax.vjp needs a pure-JAX forward"
    )

  defined = (
    {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}
    | {
      n.name
      for n in ast.walk(tree)
      if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
    }
    | {
      (a.asname or a.name).split(".")[0]
      for n in ast.walk(tree)
      if isinstance(n, (ast.Import, ast.ImportFrom))
      for a in n.names
    }
  )
  for name in RESERVED:
    if name in defined:
      raise VjpError(
        f"the forward base.py already uses the name {name!r}, which the "
        "generated wrapper needs"
      )

  if wrt:
    params = _computation_params(tree)
    if params is None:
      raise VjpError(
        "--wrt names cannot be resolved from the forward `computation`'s "
        "signature. Omit --wrt to differentiate every floating-point input."
      )
    unknown = [w for w in wrt if w not in params]
    if unknown:
      raise VjpError(
        f"--wrt names {unknown} are not parameters of the forward "
        f"`computation{tuple(params)}`"
      )
    positions = tuple(sorted(params.index(w) for w in wrt))
    wrt_desc = ", ".join(params[i] for i in positions)
  else:
    positions = None
    wrt_desc = "every floating-point array argument"

  returns, summary, body = _SUMMARIES[optimize_forward]
  out = (
    fwd_src.rstrip("\n")
    + _HEADER.format(
      marker=MARKER,
      forward=FORWARD_NAME,
      positions=positions,
      wrt_desc=wrt_desc,
      returns=returns,
      summary=summary,
    )
    + body
  )
  compile(out, "base.py", "exec")
  return out


def main():
  p = argparse.ArgumentParser(
    description="Turn a forward base.py into a training-step or backward "
    "base.py (Phase 0.85)."
  )
  p.add_argument("base_path", help="<run_dir>/base.py")
  p.add_argument(
    "--wrt",
    nargs="+",
    default=None,
    help="forward `computation` parameters to differentiate (default: all "
    "floating-point array arguments)",
  )
  p.add_argument(
    "--fixed-forward",
    action="store_true",
    help="return only the gradients: the forward stays fixed and only the "
    "backward is optimized",
  )
  args = p.parse_args()

  base = Path(args.base_path)
  fwd = base.with_name("base_fwd.py")
  source = fwd if fwd.exists() else base
  if not source.exists():
    print(f"VJP_BASE_FAILED: {base} does not exist", file=sys.stderr)
    return 1

  try:
    src = generate(source.read_text(), args.wrt, not args.fixed_forward)
  except (VjpError, SyntaxError) as e:
    print(f"VJP_BASE_FAILED: {e}", file=sys.stderr)
    return 1

  if not fwd.exists():
    shutil.copyfile(base, fwd)
  base.write_text(src)
  print(f"Wrote generated base.py at {base} (forward kept at {fwd})")
  return 0


if __name__ == "__main__":
  sys.exit(main())
