"""Runs hardware probes from `probes/` on the TPU and caches what they print.

A probe answers one question about the TPU or the Pallas/Mosaic toolchain in
front of you -- does this construct lower, how much VMEM can a kernel really
use, what does a grid step cost -- by measuring it on the target. The probes
live in `probes/checks/`; `reference/probe_catalog.md` lists every one with
the design question it answers.

    run_probe.py --list [--group partitioning]
    run_probe.py --pick vmem_scratch_bisect [--pick dispatch_floor] \
        --run_dir <run_dir>

`--list` runs locally and never touches a device. `--pick` builds one
self-contained script (the probe harness plus the needed `checks/` modules,
inlined as text) and submits it through `tpu_client.py`, the same way
`verify_port.py` ships its check: the TPU server runs source text only.

Every run is stamped with `software_versions` and `device_inventory`, and the
output is cached under `workspace/_probe_cache/<device>/<versions>/`, keyed by
what that stamp reports. A different TPU or toolchain is a cache miss, so a
number measured on one environment is never served for another. Nothing is
written into the repository.

Destructive probes can halt the Mosaic core and poison later jobs on the same
TPU, so they are refused unless `--allow-destructive` is passed. Agents must
never pass it.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROBES_DIR = ROOT / "probes"
CACHE_DIR = ROOT / "workspace" / "_probe_cache"

# Always run alongside the requested probes, so every output says which
# device and toolchain produced it. Their output is the cache key.
_STAMP_PROBES = ("software_versions", "device_inventory")

_SCRIPT_TEMPLATE = """\
# Generated by tools/run_probe.py. Self-contained: tpu_client.py submits
# source text only, so the probe harness and the needed checks/ modules are
# inlined below and written next to this script before they are imported.
import os
import sys

FILES = {files!r}

for _rel, _src in FILES.items():
  _dir = os.path.dirname(_rel)
  if _dir:
    os.makedirs(_dir, exist_ok=True)
  with open(_rel, "w") as _f:
    _f.write(_src)

sys.path.insert(0, os.getcwd())
sys.stdout.reconfigure(line_buffering=True)

import run_probes  # noqa: E402

run_probes.main({argv!r})
# FAIL is a finding, not an infrastructure error: always exit 0 so the
# client returns the output for the caller to read.
sys.exit(0)
"""


def _load_registry():
  """Imports every probe module locally and returns the registered probes."""
  sys.path.insert(0, str(PROBES_DIR))
  try:
    import harness  # noqa: PLC0415
    import run_probes  # noqa: PLC0415
  except ImportError as error:
    raise SystemExit(
      f"cannot import the probe suite from {PROBES_DIR}: {error}. "
      "Run this tool with the MaxKernel venv interpreter."
    ) from error
  run_probes._import_all_check_modules()  # pylint: disable=protected-access
  return harness.registered_probes()


def _module_of(probe) -> str:
  """`checks.partitioning` for a probe registered in checks/partitioning.py."""
  return probe.body.__module__


def _list(groups: list[str]) -> int:
  sys.path.insert(0, str(PROBES_DIR))
  import run_probes  # noqa: PLC0415

  argv = ["--list"]
  for group in groups:
    argv += ["--group", group]
  run_probes.main(argv)
  return 0


def _stamp_key(output: str) -> str | None:
  """Derives the cache key from the stamp probes' detail strings."""
  versions = re.search(r"software_versions\n.*\n\s+PASS[^:]*:\s*(.+)", output)
  devices = re.search(r"device_inventory\n.*\n\s+PASS[^:]*:\s*(.+)", output)
  if not versions or not devices:
    return None
  kinds = re.search(r"kinds=\[([^\]]*)\]", devices.group(1))
  device = (kinds.group(1) if kinds else "unknown").strip("'\" ")
  wanted = {}
  for item in versions.group(1).split():
    name, _, value = item.partition("=")
    if name in ("jax", "jaxlib", "libtpu"):
      wanted[name] = value
  version_key = "-".join(
    f"{name}{wanted.get(name, 'absent')}"
    for name in ("jax", "jaxlib", "libtpu")
  )
  safe = lambda text: re.sub(r"[^A-Za-z0-9._-]+", "_", text)  # noqa: E731
  return f"{safe(device)}/{safe(version_key)}"


def _split_by_probe(output: str, names: list[str]) -> dict[str, str]:
  """Cuts each probe's report out of the combined output.

  A report is a `[group] name` header, the question, and the verdict line,
  whose detail string may run over several lines. It ends at the next
  report header or at the suite's closing `====` rule.
  """
  blocks = {}
  for name in names:
    header = re.search(rf"\n\[[^\]]+\] {re.escape(name)}\n", output)
    if not header:
      continue
    start = header.start() + 1
    ends = [
      pos
      for pos in (
        output.find("\n\n[", header.end()),
        output.find("\n" + "=" * 20, header.end()),
      )
      if pos != -1
    ]
    end = min(ends) if ends else len(output)
    blocks[name] = output[start:end].strip("\n")
  return blocks


def _config_digest(tpu_config: str | None) -> str:
  """Identifies which TPU(s) this client talks to, for the cache key file."""
  path = Path(tpu_config) if tpu_config else ROOT / "tpu_config.json"
  try:
    return hashlib.sha1(path.read_bytes()).hexdigest()[:12]
  except OSError:
    return "default"


def _cached(key_file: Path, names: list[str]) -> dict[str, str]:
  """Returns cached results for `names` under the last stamp seen, if any."""
  if not key_file.exists():
    return {}
  stamp = key_file.read_text().strip()
  found = {}
  for name in names:
    path = CACHE_DIR / stamp / f"{name}.txt"
    if path.exists():
      found[name] = path.read_text()
  return found


def _run(args) -> int:
  probes = {probe.name: probe for probe in _load_registry()}
  unknown = [name for name in args.pick if name not in probes]
  if unknown:
    print(
      f"unknown probe name(s): {', '.join(unknown)}. Names are exact; see "
      "--list or reference/probe_catalog.md.",
      file=sys.stderr,
    )
    return 2
  destructive = [name for name in args.pick if probes[name].destructive]
  if destructive and not args.allow_destructive:
    print(
      f"refusing destructive probe(s): {', '.join(destructive)}. They can "
      "halt the Mosaic core and break later jobs on this TPU.",
      file=sys.stderr,
    )
    return 2

  # The cache is keyed by the environment the probes ran on. The last stamp
  # seen for this TPU config is remembered so a repeat question costs no job;
  # the stamp is re-measured whenever a job runs. Pointing the client at a
  # different TPU config starts from an empty key, so nothing measured on one
  # TPU is served for another. Pass --no_cache after changing the toolchain
  # on the same TPU.
  key_file = CACHE_DIR / f"last_stamp_{_config_digest(args.tpu_config)}.txt"
  cached = {} if args.no_cache else _cached(key_file, args.pick)
  todo = [name for name in args.pick if name not in cached]

  results = dict(cached)
  stamp = key_file.read_text().strip() if key_file.exists() else None
  if todo:
    names = list(_STAMP_PROBES) + [n for n in todo if n not in _STAMP_PROBES]
    modules = {"checks.environment"} | {_module_of(probes[n]) for n in todo}
    files = {
      "harness.py": (PROBES_DIR / "harness.py").read_text(),
      "run_probes.py": (PROBES_DIR / "run_probes.py").read_text(),
      "checks/__init__.py": (PROBES_DIR / "checks" / "__init__.py").read_text(),
    }
    for module in sorted(modules):
      rel = module.replace(".", "/") + ".py"
      files[rel] = (PROBES_DIR / rel).read_text()
    argv = ["--traceback"]
    for name in names:
      argv += ["--pick", name]
    if args.allow_destructive:
      argv.append("--include-destructive")
    script = _SCRIPT_TEMPLATE.format(files=files, argv=argv)

    with tempfile.TemporaryDirectory() as tmp:
      digest = hashlib.sha1("".join(names).encode()).hexdigest()[:10]
      script_path = Path(tmp) / f"run_probe_{digest}.py"
      script_path.write_text(script)
      command = [
        sys.executable,
        str(ROOT / "tools" / "tpu_client.py"),
        "--action",
        "performance_test",
        "--code_file",
        str(script_path),
        "--timeout",
        str(args.timeout),
      ]
      if args.tpu_config:
        command += ["--tpu_config", args.tpu_config]
      proc = subprocess.run(
        command,
        capture_output=True,
        text=True,
        timeout=args.timeout + 600,
        check=False,
      )
    output = proc.stdout or ""
    if "probe suite: 0 of" in output or "probe suite:" not in output:
      print(output[-4000:])
      print((proc.stderr or "")[-2000:], file=sys.stderr)
      print("probe job did not run any probe; see the output above.")
      return 1

    stamp = _stamp_key(output) or "unstamped"
    blocks = _split_by_probe(output, names)
    for name, block in blocks.items():
      results[name] = block
      if not args.no_cache and stamp != "unstamped":
        path = CACHE_DIR / stamp / f"{name}.txt"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(block + "\n")
    if not args.no_cache and stamp != "unstamped":
      key_file.parent.mkdir(parents=True, exist_ok=True)
      key_file.write_text(stamp + "\n")
    missing = [name for name in todo if name not in blocks]
    if missing:
      print(output[-4000:])
      print(f"no result found for: {', '.join(missing)}", file=sys.stderr)

  if args.run_dir:
    out_dir = Path(args.run_dir) / "probes"
    out_dir.mkdir(parents=True, exist_ok=True)
  print(f"environment: {stamp or 'unknown'}")
  for name in args.pick:
    if name not in results:
      continue
    source = "cache" if name in cached else "ran"
    print(f"\n# {name} ({source})\n{results[name].rstrip()}")
    if args.run_dir:
      (out_dir / f"{name}.txt").write_text(
        f"environment: {stamp or 'unknown'}\n{results[name].rstrip()}\n"
      )
  return 0 if all(name in results for name in args.pick) else 1


def main(argv: list[str] | None = None) -> int:
  parser = argparse.ArgumentParser(
    description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
  )
  parser.add_argument(
    "--list", action="store_true", help="Print the registry and exit."
  )
  parser.add_argument(
    "--group", action="append", default=[], help="With --list: one group."
  )
  parser.add_argument(
    "--pick",
    action="append",
    default=[],
    help="Run the probe with this exact name on the TPU. Repeatable.",
  )
  parser.add_argument(
    "--run_dir", help="Also write each result to <run_dir>/probes/<name>.txt."
  )
  parser.add_argument(
    "--timeout", type=int, default=600, help="Seconds for the probe job."
  )
  parser.add_argument(
    "--no_cache", action="store_true", help="Ignore and do not write the cache."
  )
  parser.add_argument(
    "--allow-destructive",
    dest="allow_destructive",
    action="store_true",
    help="Permit probes that can halt the TPU core. Never pass this from an "
    "agent.",
  )
  parser.add_argument("--tpu_config", help="Passed through to tpu_client.py.")
  args = parser.parse_args(argv)

  if args.list:
    return _list(args.group)
  if not args.pick:
    parser.error("pass --list, or one or more --pick <probe_name>")
  return _run(args)


if __name__ == "__main__":
  sys.exit(main())
