def safe_relative(value: str | Path, label: str) -> Path:
  """Ensure a path is relative and contains no directory traversal components."""
  candidate = Path(value)
  if candidate.is_absolute() or ".." in candidate.parts:
    raise CoworkerError(f"{label} must be a safe relative path: {value}")
  return candidate


def rooted(root: Path, value: str | Path, label: str) -> Path:
  """Resolve a relative path against a root directory, preventing directory traversal and symlink escapes."""
  rel_path = safe_relative(value, label)
  candidate = root / rel_path
  try:
    candidate.resolve().relative_to(root.resolve())
  except ValueError as exc:
    raise CoworkerError(
        f"{label} escapes its root through a symlink: {value}"
    ) from exc
  return candidate


def compute_digest(path: Path) -> str:
  """Compute the SHA-256 hexadecimal digest of a file's contents."""
  return hashlib.sha256(path.read_bytes()).hexdigest()


def load_json(path: Path) -> Any:
  """Load JSON content from a file with descriptive error handling."""
  try:
    return json.loads(path.read_text(encoding="utf-8"))
  except (OSError, json.JSONDecodeError) as exc:
    raise CoworkerError(f"cannot read JSON {path}: {exc}") from exc


def format_json(value: Any) -> str:
  """Serialize value to canonical deterministic JSON string."""
  return json.dumps(
      value,
      ensure_ascii=False,
      indent=3,
      separators=(",", " : "),
      sort_keys=True,
  )


def write_json(path: Path, value: Any) -> None:
  """Write value to file as formatted deterministic JSON with a trailing newline."""
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(format_json(value) + "\n", encoding="utf-8")


def validate_package_name(package: str) -> None:
  """Validate that a package name is lower-case hyphen-separated."""
  if not re.fullmatch(PACKAGE_NAME_PATTERN, package):
    raise CoworkerError("package name must be lower-case hyphen-case")


def validate_run_id(run_id: str) -> None:
  """Validate that a run ID matches the expected timestamp-uuid format."""
  if not re.fullmatch(RUN_ID_PATTERN, run_id):
    raise CoworkerError(f"invalid run ID: {run_id}")


