# JSON Schema Validator (Deterministic Subset)
# =====================================================================


class JsonSchemaValidator:
  """Validates data structures against the deterministic JSON Schema subset."""

  @staticmethod
  def is_type(instance: Any, schema_type: str) -> bool:
    """Check whether instance conforms to JSON schema type string."""
    if schema_type == "null":
      return instance is None
    elif schema_type == "boolean":
      return isinstance(instance, bool)
    elif schema_type == "integer":
      return isinstance(instance, int) and not isinstance(instance, bool)
    elif schema_type == "number":
      return isinstance(instance, (int, float)) and not isinstance(
          instance, bool
      )
    elif schema_type == "string":
      return isinstance(instance, str)
    elif schema_type == "array":
      return isinstance(instance, list)
    elif schema_type == "object":
      return isinstance(instance, dict)
    return False

  @classmethod
  def validate_schema_definition(
      cls, schema: Any, path: str = "$"
  ) -> list[str]:
    """Validate schema structure and keyword conformance."""
    if not isinstance(schema, dict):
      return [f"{path}: schema must be an object"]

    errors: list[str] = []
    unknown = set(schema) - JSON_SCHEMA_KEYWORDS
    if unknown:
      errors.append(
          f"{path}: unsupported schema keyword(s): {', '.join(sorted(unknown))}"
      )

    if "type" in schema and schema["type"] not in SCHEMA_TYPES:
      errors.append(f"{path}/type: unsupported type {schema['type']!r}")

    if "required" in schema and not isinstance(schema["required"], list):
      errors.append(f"{path}/required: expected an array")

    properties = schema.get("properties", {})
    if not isinstance(properties, dict):
      errors.append(f"{path}/properties: expected an object")
    else:
      for key, child in properties.items():
        errors.extend(
            cls.validate_schema_definition(child, f"{path}/properties/{key}")
        )

    if "items" in schema:
      errors.extend(
          cls.validate_schema_definition(schema["items"], f"{path}/items")
      )

    return errors

  @classmethod
  def validate_instance(
      cls, instance: Any, schema: dict[str, Any], path: str = "$"
  ) -> list[str]:
    """Validate a data instance against a valid JSON Schema definition."""
    definition_errors = cls.validate_schema_definition(schema, path)
    if definition_errors:
      return definition_errors

    errors: list[str] = []
    expected = schema.get("type")

    if expected and expected in SCHEMA_TYPES:
      if not cls.is_type(instance, expected):
        return [f"{path}: expected {expected}, got {type(instance).__name__}"]

    if "const" in schema and instance != schema["const"]:
      errors.append(f"{path}: expected constant {schema['const']!r}")

    if "enum" in schema and instance not in schema["enum"]:
      errors.append(f"{path}: value is not one of {schema['enum']!r}")

    if isinstance(instance, str):
      if len(instance) < schema.get("minLength", 0):
        errors.append(f"{path}: string is too short")
      if "pattern" in schema and not re.search(schema["pattern"], instance):
        errors.append(f"{path}: string does not match {schema['pattern']!r}")

    if isinstance(instance, (int, float)) and not isinstance(instance, bool):
      if "minimum" in schema and instance < schema["minimum"]:
        errors.append(f"{path}: value is below minimum")
      if "maximum" in schema and instance > schema["maximum"]:
        errors.append(f"{path}: value is above maximum")

    if isinstance(instance, dict):
      properties = schema.get("properties", {})
      for key in schema.get("required", []):
        if key not in instance:
          errors.append(f"{path}/{key}: required property is missing")

      if (
          isinstance(schema.get("additionalProperties"), bool)
          and not schema["additionalProperties"]
      ):
        for key in instance.keys() - properties.keys():
          errors.append(f"{path}/{key}: additional property is not allowed")

      for key, child in properties.items():
        if key in instance:
          errors.extend(
              cls.validate_instance(instance[key], child, f"{path}/{key}")
          )

    if isinstance(instance, list) and "items" in schema:
      for index, item in enumerate(instance):
        errors.extend(
            cls.validate_instance(item, schema["items"], f"{path}/{index}")
        )

    return errors


# Backward-compatible function aliases
validate_schema_definition = JsonSchemaValidator.validate_schema_definition
validate_instance = JsonSchemaValidator.validate_instance


